def _init_state():
    st.session_state.setdefault("lab_files", {})
    st.session_state.setdefault("lab_step", 0)
    st.session_state.setdefault("lab_messages", {})


def _validate_python(source):
    try:
        ast.parse(source)
        return True, "Python syntax is valid."
    except SyntaxError as exc:
        return False, f"Python syntax error on line {exc.lineno}: {exc.msg}"


def _validate_file(filename, source, required):
    if filename.endswith(".py"):
        ok, message = _validate_python(source)
        if not ok:
            return False, message
    if filename.endswith(".json"):
        try:
            data = json.loads(source)
            if not isinstance(data, list) or not data:
                return False, "Golden JSON must contain at least one test case."
        except Exception as exc:
            return False, f"JSON is not valid: {exc}"
    missing = [token for token in required if token not in source]
    if missing:
        return False, "Still missing: " + ", ".join(missing)
    return True, "Step complete — the important building blocks are present."


def _project_zip(files):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, content in files.items():
            archive.writestr(path, content)
        archive.writestr(
            "tests/data/training_policy.txt",
            "Password reset links expire after 30 minutes.\n\n"
            "Items may be returned within 30 days only if unopened.\n\n"
            "New employees must complete their first 90 days in the office before remote work begins.\n",
        )
    return buffer.getvalue()


