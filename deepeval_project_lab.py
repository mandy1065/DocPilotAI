from dataclasses import dataclass

from openai import OpenAI
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity


@dataclass
class RAGResult:
    # Keep the original user question for traceability.
    input: str
    # Store the answer generated by the LLM.
    answer: str
    # Store the exact chunks returned by retrieval for DeepEval metrics.
    retrieval_context: list[str]


class RAGPipeline:
    def __init__(self, chunks, top_k=4, model="gpt-4.1-mini"):
        # Save the searchable chunks used by the retriever.
        self.chunks = chunks
        # Save how many chunks should be returned for each question.
        self.top_k = top_k
        # Save the model used to generate the final answer.
        self.model = model
        # Create a lightweight TF-IDF vectorizer for the classroom RAG pipeline.
        self.vectorizer = TfidfVectorizer(stop_words="english", ngram_range=(1, 2))
        # Convert every document chunk into a searchable numeric representation.
        self.matrix = self.vectorizer.fit_transform(chunks)

    @staticmethod
    def chunk_text(text, size=1200, overlap=200):
        # Hold all document chunks that we create.
        chunks = []
        # Start reading from the beginning of the document.
        start = 0
        # Continue until the complete document has been chunked.
        while start < len(text):
            # Calculate the end position without going beyond the document.
            end = min(start + size, len(text))
            # Extract and clean one chunk.
            piece = text[start:end].strip()
            # Keep only non-empty chunks.
            if piece:
                chunks.append(piece)
            # Stop after processing the final chunk.
            if end >= len(text):
                break
            # Move forward while keeping overlap with the previous chunk.
            start = end - overlap
        # Return all chunks to the caller.
        return chunks

    @classmethod
    def from_text(cls, text, top_k=4):
        # Split source text into chunks first.
        chunks = cls.chunk_text(text)
        # Build and return an indexed RAG pipeline.
        return cls(chunks, top_k=top_k)

    def retrieve(self, question):
        # Convert the user question into the same TF-IDF space as the chunks.
        query = self.vectorizer.transform([question])
        # Compare the question with every stored chunk.
        scores = cosine_similarity(query, self.matrix).flatten()
        # Sort the chunks from highest similarity to lowest and keep Top-K.
        order = scores.argsort()[::-1][: self.top_k]
        # Return the selected source text in ranked order.
        return [self.chunks[i] for i in order]

    def ask(self, question):
        # Retrieve evidence before asking the language model.
        context = self.retrieve(question)
        # Create the OpenAI client from the environment secret.
        client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])
        # Join the retrieved chunks into one prompt context block.
        joined = "\n\n---\n\n".join(context)
        # Tell the LLM to remain grounded in the retrieved document context.
        prompt = f"""Answer only from the supplied context.
If the answer is missing, say: I don't know based on the uploaded document.

CONTEXT:
{joined}

QUESTION:
{question}"""
        # Send the grounded prompt to the model.
        response = client.responses.create(model=self.model, input=prompt)
        # Return both generation output and retrieval evidence for evaluation.
        return RAGResult(question, response.output_text.strip(), context)
